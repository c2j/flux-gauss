CREATE OR REPLACE PACKAGE PKG_F_MAPPER_DUPLICATE AS
  PROCEDURE prc_dynamic(p_id IN NUMBER);
END PKG_F_MAPPER_DUPLICATE;
/

CREATE OR REPLACE PACKAGE BODY PKG_F_MAPPER_DUPLICATE AS
  PROCEDURE prc_dynamic(p_id IN NUMBER) IS
    v_sql VARCHAR2(4000);
    v_value NUMBER;
    n NUMBER := 1;
  BEGIN
    v_sql := 'SELECT 1 FROM dual WHERE 1 = :n';
    EXECUTE IMMEDIATE v_sql INTO v_value USING n;
  END prc_dynamic;
END PKG_F_MAPPER_DUPLICATE;
/
